# ------------------------------------------------------------------ validation
def validate():
    problems = []
    ids = [f.id for f in C.FOCUSES]
    if len(ids) != len(set(ids)):
        problems.append("duplicate focus IDs")
    known = set(ids) | {"FCU_ur_assessment"}
    for f in C.FOCUSES:
        if not re.fullmatch(r"FCU_ud_\w+", f.id):
            problems.append("bad ID " + f.id)
        if f.cost not in (5, 10):
            problems.append("cost %s on %s" % (f.cost, f.id))
        for group in f.pre:
            for p in group:
                if p not in known:
                    problems.append("%s: unknown prerequisite %s" % (f.id, p))
                elif p in FOCUS and FOCUS[p].y >= f.y:
                    problems.append("%s: prerequisite %s is not above it" % (f.id, p))
        for e in f.excl:
            if e not in FOCUS:
                problems.append("%s: unknown exclusive %s" % (f.id, e))
        for subject in f.subj:
            if subject not in seams.SUBJECTS:
                problems.append("%s: unknown art subject %s" % (f.id, subject))
        if f.tree == C.OPENING and not (f.x <= 23 and f.y >= 6):
            problems.append("%s outside the opening band" % f.id)
        if f.tree == C.WAR and not 42 <= f.x <= 94:
            problems.append("%s outside the war band" % f.id)
        if f.regime and f.ai:
            problems.append("%s reaches a regime effect with AI weight %d" % (f.id, f.ai))
        for idea in re.findall(r"(?:add_ideas|remove_ideas|idea) = (FCU_ud_\w+)", f.reward):
            if idea not in IDEAS:
                problems.append("%s: undefined idea %s" % (f.id, idea))
        for number in re.findall(r"id = ac_ud_fcu\.(\d+)", f.reward):
            if int(number) not in N.EVENTS:
                problems.append("%s: undefined event %s" % (f.id, number))
    for tree in (C.OPENING, C.WAR):
        nodes = [f for f in C.FOCUSES if f.tree == tree]
        for a in nodes:
            for b in nodes:
                if a.id < b.id and a.y == b.y and abs(a.x - b.x) < 2:
                    problems.append("caption overlap %s / %s" % (a.id, b.id))
    for number, e in N.EVENTS.items():
        bodies = [p for _, p in e["variants"]] or [e["paragraphs"]]
        for paragraphs in bodies:
            for problem in seams.event_problems(seams.event_text(paragraphs, e["layer"], e["cite"])):
                problems.append("event %d: %s" % (number, problem))
        if e["picture"] not in PICTURES:
            problems.append("event %d: unknown picture %s" % (number, e["picture"]))
    used = {int(n) for f in C.FOCUSES for n in re.findall(r"id = ac_ud_fcu\.(\d+)", f.reward)} | {26, 30}
    if used != set(N.EVENTS):
        problems.append("events never fired or missing: %s" % sorted(set(N.EVENTS) ^ used))
    return problems


