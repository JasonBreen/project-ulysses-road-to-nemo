NOTE='# Generated by tools/air_program/build.py. Names, dates and specifications are provisional gameplay.\n'
STATS=('build_cost_ic','fuel_consumption','manpower','maximum_speed','air_range','air_agility','air_attack','air_defence','air_ground_attack','air_bombing','naval_strike_attack','naval_strike_targetting','surface_detection','sub_detection','air_superiority','reliability','weight','thrust')


def block(key,text):return key+' = {\n'+'\n'.join('\t'+line if line.strip() else '' for line in text.splitlines())+'\n}\n'
def number(v):return format(v,'.9g') if isinstance(v,float) else str(v)
def fields(values):return '\n'.join(k+' = '+number(v) for k,v in values.items())+'\n'
def names(values):return '\n'.join(values)


def values(kind,tier,field='add'):
    row=MODULES[kind];step=row.get('step' if field=='add' else field+'_step',{})
    return {k:round(v+tier*step.get(k,0),7) for k,v in row.get(field,{}).items()}


def base_stats(family,tier):
    stats=dict.fromkeys(STATS,0);stats.update(reliability=.86+.015*tier)
    if family=='transport':
        stats.update(build_cost_ic=70+10*tier,fuel_consumption=.8+.05*tier,manpower=80,maximum_speed=750+50*tier,
            air_range=2600+500*tier,air_agility=15+tier,air_defence=28+4*tier)
    else:
        stats.update(build_cost_ic=(30+3*tier if family=='surveillance' else 18+2*tier),fuel_consumption=.05,
            manpower=40 if family=='surveillance' else 20,maximum_speed={'fighter':1000,'strike':850,'maritime':800,'surveillance':650}[family]+(50 if family!='maritime' else 40)*tier,
            air_range={'fighter':1800,'strike':1500,'maritime':2400,'surveillance':3200}[family]+{'fighter':300,'strike':250,'maritime':400,'surveillance':500}[family]*tier,
            air_agility={'fighter':60,'strike':35,'maritime':30,'surveillance':25}[family]+(4 if family=='fighter' else 2)*tier,
            air_defence=24+4*tier,air_superiority=0 if family=='surveillance' else 1,
            weight=18 if family=='surveillance' else 10)
        if family=='surveillance':stats.update(surface_detection=60+10*tier,sub_detection=15+2*tier)
    return stats


def base_resources(family):return dict(aluminium=5,rubber=2,chromium=1) if family=='transport' else dict(aluminium=4,rubber=2) if family=='surveillance' else dict(aluminium=3,rubber=1)


def complete(family,tier):
    stats=base_stats(family,tier);resources=Counter(base_resources(family));multipliers=Counter()
    for module in recipe(family,YEARS[tier]).values():
        kind=module.removeprefix('ac_air_').rsplit('_',1)[0]
        for key,value in values(kind,tier).items():stats[key]=round(stats.get(key,0)+value,7)
        for key,value in values(kind,tier,'average').items():stats[key]=round(stats.get(key,0)+value,7)
        multipliers.update(values(kind,tier,'multiply'));resources.update(MODULES[kind]['resources'])
    stats={k:round(v*(1+multipliers[k]),7) for k,v in stats.items()}
    return stats,dict(resources)


def module_output():
    text=NOTE
    for kind,row in MODULES.items():
        for tier,year in enumerate(YEARS):
            body=f'abbreviation = "A{tier+1}"\ncategory = {row["category"]}\nxp_cost = 3\ndismantle_cost_ic = 1\n'
            if tier:body+='parent = '+module_id(kind,YEARS[tier-1])+'\n'
            if row.get('equipment_type'):body+='add_equipment_type = '+row['equipment_type']+'\n'
            if row.get('missions'):body+=block('allow_mission_type',names(row['missions']))
            if kind=='camera':body+=block('forbid_equipment_type_exact_match_for_category','\n'.join(k+' = scout_plane' for k in ('fighter_weapon','cas_weapon','nav_bomber_weapon','tac_weapon','mine_warfare_offense')))
            for source,target in [('add','add_stats'),('average','add_average_stats'),('multiply','multiply_stats')]:
                if values(kind,tier,source):body+=block(target,fields(values(kind,tier,source)))
            body+=block('build_cost_resources',fields(row['resources']))
            text+=block(module_id(kind,year),body)
    return block('equipment_modules',text)


def mission_fields(family,legacy=False):
    row=FAMILY[family]
    return block('allow_mission_type',names(LEGACY_MISSIONS[family] if legacy else row.missions))+(block('forbid_mission_type','training') if family=='surveillance' else '')


def presentation(family):
    frame,index,sprite=ROLE_PRESENTATION[family]
    return f'air_map_icon_frame = {frame}\ninterface_overview_category_index = {index}\nsprite = {sprite}\n'


def equipment_output():
    text=NOTE
    for row in AIRCRAFT:
        for tier,year in enumerate(YEARS):
            ident=model_id(row.id,year);parent=model_id(row.id,YEARS[tier-1]) if tier else row.parent
            body=f'year = {year}\nactive = no\nis_buildable = yes\npriority = {200+tier*10}\narchetype = {row.archetype}\nparent = {parent}\ntype = {row.equipment_type}\npicture = {ident}\n'
            gate=('NOT = { has_dlc = "By Blood Alone" }\n' if row.airframe_parent else '')+('has_dlc = "La Resistance"\n' if row.id=='surveillance' else '')
            if gate:body+=block('can_be_produced',gate)
            else:body+=block('can_be_produced','always = yes')
            stats,resources=complete(row.id,tier);body+=fields(stats)+block('resources',fields(resources))+mission_fields(row.id,True)+presentation(row.id)
            text+=block(ident,body)
            if not row.airframe_parent:continue
            parent=frame_id(row.id,YEARS[tier-1]) if tier else row.airframe_parent
            body=f'year = {year}\nactive = no\nis_buildable = no\npriority = {2100+tier*10}\narchetype = {row.archetype}\nparent = {parent}\ntype = {row.equipment_type}\npicture = {ident}\nderived_variant_name = {ident}\nmodule_slots = inherit\n'
            body+=block('can_be_produced','has_dlc = "By Blood Alone"\n'+('has_dlc = "La Resistance"' if row.id=='surveillance' else ''))
            body+=fields(base_stats(row.id,tier))+block('resources',fields(base_resources(row.id)))+mission_fields(row.id)+presentation(row.id)
            body+=block('default_modules',fields(recipe(row.id,year)))
            # These category limits also cover our new module IDs, rather than
            # relying only on inherited limits naming old individual modules.
            for category in ('fighter_weapon','cas_weapon','nav_bomber_weapon','recon_camera'):
                body+=block('module_count_limit',f'category = {category}\ncount < 2')
            text+=block(frame_id(row.id,year),body)
    return block('equipments',text)


def foundation(family):
    row=FAMILY[family]
    if not row.legacy_foundation:return ''
    legacy=block('AND','NOT = { has_dlc = "By Blood Alone" }\nhas_tech = '+row.legacy_foundation)
    designer=block('AND','has_dlc = "By Blood Alone"\nhas_tech = '+row.designer_foundation+('\nhas_tech = photo_reconnaisance' if family=='surveillance' else ''))
    return block('OR',legacy+designer)


def technology_output():
    text=NOTE
    for row in TECHS:
        family=row['family'];year=row['year'];tier=row['tier'];required=common_dependencies(family,tier)
        body=f'start_year = {year}\nresearch_cost = {2+.25*tier:g}\n'
        gate=f'date > "{year-1}.12.31"\n'+''.join('has_tech = '+v+'\n' for v in required)
        if family=='surveillance':gate+='has_dlc = "La Resistance"\n'
        if tier==0:gate+=foundation(family)
        body+=block('allow',gate)+block('dependencies','\n'.join(v+' = 1' for v in required))
        body+=block('folder',f'name = ac_air_folder\nposition = {{ x = {tier*4} y = 0 }}')
        body+=block('categories','ac_air_category\nac_air_'+family+'_category\nair_equipment')
        if tier<3:body+=block('path',f'leads_to_tech = {tech_id(family,YEARS[tier+1])}\nresearch_cost_coeff = 1')
        if family!='systems':body+=block('enable_equipments',model_id(family,year)+('\n'+frame_id(family,year) if family!='transport' else ''))
        if unlocks(family,year):body+=block('enable_equipment_modules',names(unlocks(family,year)))
        body+=block('ai_will_do','factor = 2\n'+block('modifier',f'factor = 0\ndate < "{year}.1.1"'))
        text+=block(row['id'],body)
    return block('technologies',text)


def ai_output():
    designs=NOTE;strategies=NOTE
    for row,role in [(FAMILY['fighter'],'air_fighter'),(FAMILY['strike'],'air_cas'),(FAMILY['maritime'],'air_naval_bomber'),(FAMILY['surveillance'],'air_scout_plane')]:
        priority='factor = 1200\n'+block('modifier','factor = 0\nNOT = { has_tech = '+tech_id(row.id,2006)+' }')+block('modifier','factor = 0\ndate < "2006.1.1"')
        body='category = air\navailable_for = {}\n'+block('roles',role)+block('priority',priority)
        for tier,year in enumerate(YEARS):
            gate=f'date > "{year-1}.12.31"\nhas_dlc = "By Blood Alone"\nhas_tech = {tech_id(row.id,year)}\nhas_tech = {tech_id("systems",year)}\n'
            if row.id=='surveillance':gate+='has_dlc = "La Resistance"\n'
            design=block('priority',f'factor = {10+tier*10}')+block('enable',gate)+'history = yes\n'
            design+=block('target_variant',f'match_value = {5000+tier*100}\ntype = {frame_id(row.id,year)}\n'+block('modules',fields(recipe(row.id,year))))
            design+=block('allowed_modules',names(recipe(row.id,year).values()))
            body+=block(tech_id(row.id,year)+'_design',design)
        designs+=block('ac_air_'+row.id+'_designs',body)
        gate=f'date > "2005.12.31"\nhas_tech = {tech_id(row.id,2006)}\n'+('has_dlc = "La Resistance"\n' if row.id=='surveillance' else '')
        strategies+=block('ac_air_'+row.id+'_replacement','allowed = { always = yes }\n'+block('enable',gate)+'abort_when_not_enabled = yes\n'+block('ai_strategy',f'type = equipment_production_factor\nid = {row.equipment_type}\nvalue = 5'))
    transport='date > "2005.12.31"\nhas_tech = ac_air_transport_2006\nnum_of_military_factories > 20\nhas_equipment = { transport_plane_equipment < 21 }\n'
    strategies+=block('ac_air_transport_buffer','allowed = { always = yes }\n'+block('enable',transport)+'abort_when_not_enabled = yes\n'+block('ai_strategy','type = equipment_production_min_factories_archetype\nid = transport_plane_equipment\nvalue = 1'))
    plan=block('ac_air_research','name = ac_air_research_name\ndesc = ac_air_research_desc\nallowed = { always = yes }\nenable = { date > "2005.12.31" }\nabort_when_not_enabled = yes\nresearch = { ac_air_category = 15 }\nweight = { factor = 1 }')
    return designs,strategies,NOTE+plan


