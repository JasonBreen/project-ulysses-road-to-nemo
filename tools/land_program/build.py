NOTE='# Generated by tools/land_program/build.py. All dates, labels and statistics are provisional gameplay.\n'


def block(name,text):return name+' = {\n'+'\n'.join('\t'+v if v.strip() else '' for v in text.splitlines())+'\n}\n'
def scalar(value):return format(value,'.8g') if isinstance(value,float) else str(value)
def fields(values):return '\n'.join(k+' = '+scalar(v) for k,v in values.items())+'\n'
def items(values):return '\n'.join(values)


def module_values(kind,tier):
    row=MODULES[kind]
    return {k:round(v+row['step'].get(k,0)*tier,6) for k,v in row['stats'].items()}


def platform_base(family,tier):
    if family=='mbt':
        return dict(maximum_speed=7+.3*tier,reliability=.88,fuel_consumption=1+.3*tier,
            defense=10+tier,breakthrough=55+7*tier,hardness=.98,armor_value=85+8*tier,
            soft_attack=10+tier,hard_attack=5+tier,ap_attack=10,air_attack=0,build_cost_ic=15+1.75*tier)
    return dict(maximum_speed=6.5+.3*tier,reliability=.88,fuel_consumption=.2+.3*tier,
        defense=17+2*tier,breakthrough=22+2*tier,hardness=.8,armor_value=25+3*tier,
        soft_attack=10+tier,hard_attack=3+tier,ap_attack=5,air_attack=0,build_cost_ic=14+1.75*tier)


def platform_resources(family):return dict(steel=2,chromium=2 if family=='mbt' else 1)


def platform_complete(family,tier):
    values=platform_base(family,tier);resources=platform_resources(family)
    for module in recipe(family,YEARS[tier]).values():
        kind=module.removeprefix('ac_land_').rsplit('_',1)[0]
        for k,v in module_values(kind,tier).items():values[k]=round(values.get(k,0)+v,6)
        for k,v in MODULES[kind]['resources'].items():resources[k]=resources.get(k,0)+v
    return values,resources


def module_output():
    text=NOTE
    for kind,row in MODULES.items():
        for tier,year in enumerate(YEARS):
            body=f'abbreviation = "L{tier+1}"\ncategory = {row["category"]}\nxp_cost = 2\ndismantle_cost_ic = 0.5\n'
            if tier:body+='parent = '+module_id(kind,YEARS[tier-1])+'\n'
            if kind in ('turret','artillery_turret'):
                body+=block('allowed_module_categories',block('main_armament_slot','tank_heavy_main_armament\ntank_medium_main_armament'))
            if kind=='howitzer':body+='allow_equipment_type = artillery\n'
            body+=block('add_stats',fields(module_values(kind,tier)))
            body+=block('build_cost_resources',fields(row['resources']))
            text+=block(module_id(kind,year),body)
    return block('equipment_modules',text)


def conventional(family,tier):
    if family=='infantry':return 'infantry_equipment','infantry_equipment_3',dict(defense=36+4*tier,breakthrough=6+tier,soft_attack=14+2*tier,hard_attack=2.5+.5*tier,ap_attack=16+6*tier,air_attack=0,reliability=.88,maximum_speed=4,build_cost_ic=.95+.12*tier),dict(steel=3+tier//2,aluminium=1)
    if family=='mobility':return 'mechanized_equipment','mechanized_equipment_3',dict(defense=40+5*tier,breakthrough=10+2*tier,hardness=.7,armor_value=25+5*tier,soft_attack=8+2*tier,hard_attack=5+tier,ap_attack=20+5*tier,reliability=.85+.02*tier,maximum_speed=12,fuel_consumption=2.8+.1*tier,build_cost_ic=16+3*tier),dict(steel=3,rubber=2,chromium=1)
    if family=='support':return 'support_equipment','support_equipment_1',dict(reliability=.85+.02*tier,build_cost_ic=5+.75*tier),dict(steel=2,aluminium=2)
    if family=='logistics':return 'motorized_equipment','motorized_equipment_1',dict(reliability=.9+.015*tier,maximum_speed=12,fuel_consumption=1.1-.03*tier,build_cost_ic=3.5+.5*tier),dict(steel=1,rubber=1)
    if family=='surveillance':return 'ac_land_sensor_equipment',None,dict(reliability=.85+.02*tier,fuel_consumption=0,build_cost_ic=8+2*tier),dict(aluminium=2,steel=1,rubber=1)
    if family=='electronic_support':return 'ac_land_electronic_equipment',None,dict(reliability=.85+.02*tier,fuel_consumption=0,build_cost_ic=10+2*tier),dict(aluminium=2,steel=1,rubber=1)
    raise ValueError(family)


def equipment_output():
    text=NOTE
    for ident in ('ac_land_sensor_equipment','ac_land_electronic_equipment'):
        body=f'year = 2006\nis_archetype = yes\nis_buildable = no\nactive = yes\npicture = {ident}\n'
        body+='type = { infantry motorized support }\ngroup_by = archetype\ninterface_category = interface_category_land\n'
        text+=block(ident,body)
    for family in FAMILY:
        for tier,year in enumerate(YEARS):
            ident=model_id(family,year)
            # Captured complete MBT parent is170; all complete new tiers must
            # rank above their actual inherited equipment, not below it.
            common=f'year = {year}\nactive = no\npriority = {200+10*tier}\npicture = {ident}\nis_buildable = yes\n'
            if family in ('mbt','tracked_artillery'):
                archetype='modern_tank_chassis' if family=='mbt' else 'medium_tank_artillery_chassis'
                parent='modern_tank_equipment_1' if family=='mbt' else 'medium_tank_artillery_equipment_1'
                if tier:parent=model_id(family,YEARS[tier-1])
                values,resources=platform_complete(family,tier)
                body=common+f'archetype = {archetype}\nparent = {parent}\n'+block('can_be_produced','NOT = { has_dlc = "No Step Back" }')
                body+='type = armor\n' if family=='mbt' else 'type = { armor artillery }\n'
                body+=fields(values)+block('resources',fields(resources))
                text+=block(ident,body)
                parent='modern_tank_chassis_1' if family=='mbt' else 'medium_tank_artillery_chassis_1'
                if tier:parent=chassis_id(family,YEARS[tier-1])
                body=f'year = {year}\nactive = no\npriority = {2100+10*tier}\nis_buildable = no\narchetype = {archetype}\nparent = {parent}\n'
                body+=f'picture = {ident}\nderived_variant_name = {ident}\nmodule_slots = inherit\n'
                body+=block('can_be_produced','has_dlc = "No Step Back"')
                body+='type = armor\n' if family=='mbt' else 'type = { armor artillery }\n'
                body+=fields(platform_base(family,tier))+block('resources',fields(platform_resources(family)))
                # Deliberately neutralize the inherited modern chassis attack
                # multiplier; the complete default recipe has explicit parity.
                body+=block('module_add_stats_multiplier','soft_attack = 0\nhard_attack = 0\nair_attack = 0')
                body+=block('default_modules',fields(recipe(family,year)))
                text+=block(chassis_id(family,year),body)
            else:
                archetype,parent,values,resources=conventional(family,tier)
                if tier:parent=model_id(family,YEARS[tier-1])
                body=common+f'archetype = {archetype}\n'+(f'parent = {parent}\n' if parent else '')
                body+=fields(values)+block('resources',fields(resources))
                text+=block(ident,body)
    return block('equipments',text)


def tech_output():
    text=NOTE
    for row in TECHS:
        family=row['family'];year=row['year'];tier=row['tier'];req=prerequisites(family,tier)
        body=f'start_year = {year}\nresearch_cost = {2.5+.25*tier if family in ("mbt","tracked_artillery") else 1.5+.2*tier:g}\n'
        body+=block('allow',f'date > "{year-1}.12.31"\n'+'\n'.join('has_tech = '+v for v in req))
        body+=block('dependencies','\n'.join(v+' = 1' for v in req))
        body+=block('folder',f'name = ac_land_folder\nposition = {{ x = {tier*4} y = 0 }}')
        body+=block('categories','ac_land_category\nac_land_'+family+'_category\n'+items(FAMILY[family].categories))
        if tier<3:body+=block('path',f'leads_to_tech = ac_land_{family}_{YEARS[tier+1]}\nresearch_cost_coeff = 1')
        body+=block('enable_equipments',items(models(family,year)))
        unlocked=module_unlocks(family,year)
        if unlocked:body+=block('enable_equipment_modules',items(unlocked))
        if family=='mbt':body+=block('enable_subunits','modern_armor')
        if family=='tracked_artillery':body+=block('enable_subunits','medium_sp_artillery_brigade')
        if family=='surveillance':
            body+=block('enable_subunits','ac_land_surveillance_company')
            if tier:body+=block('ac_land_surveillance_company','recon = 0.25')
        if family=='electronic_support':
            body+=block('enable_subunits','ac_land_electronic_support_company')
            if tier:body+=block('ac_land_electronic_support_company','initiative = 0.02')
        if family=='support':body+=block('engineer','entrenchment = 1')+block('maintenance_company','reliability_factor = 0.015')
        if family=='logistics':body+=block('logistics_company','supply_consumption_factor = -0.025\nfuel_consumption_factor = -0.01')
        body+=block('ai_will_do','factor = 2\n'+block('modifier',f'factor = 0\ndate < "{year}.1.1"'))
        text+=block(row['id'],body)
    return block('technologies',text)


