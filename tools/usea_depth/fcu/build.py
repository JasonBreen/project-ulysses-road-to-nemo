def reward(f):
    body = f.reward.replace("%ID%", f.id)
    extra = []
    if f.regime:
        extra.append("custom_effect_tooltip = FCU_ud_regime_tt")
    if f.id == "FCU_ud_ulysses_warning":
        extra.append("custom_effect_tooltip = FCU_ud_readiness_tt")
    inner = "set_country_flag = %s_done\n" % f.id + "\n".join(extra + [body])
    return "if = {\n\tlimit = { %s NOT = { has_country_flag = %s_done } }\n%s\n}" % (
        available(f), f.id, "\n".join("\t" + line for line in inner.splitlines()))


def focus_text(f):
    lines = ["id = " + f.id, "icon = GFX_ac_ud_focus_" + f.id, "x = %d" % f.x, "y = %d" % f.y, "cost = %d" % f.cost,
             "ai_will_do = { factor = %d }" % f.ai]
    for group in f.pre:
        lines.append("prerequisite = { %s }" % " ".join("focus = " + p for p in group))
    if EXCL.get(f.id):
        lines.append("mutually_exclusive = { %s }" % " ".join("focus = " + e for e in sorted(EXCL[f.id])))
    lines.append("available = { %s }" % available(f))
    lines += ["cancel_if_invalid = yes", "continue_if_invalid = no"]
    body = "\n".join(lines) + "\n" + block("completion_reward", reward(f)) + "search_filters = { }"
    return block("shared_focus", body)


