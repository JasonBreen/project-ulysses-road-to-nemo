def ai_design_output():
    text=NOTE
    for family,role in [('mbt','land_modern_tank'),('tracked_artillery','land_medium_tank_artillery')]:
        priority='factor = 1200\n'+block('modifier',f'factor = 0\nNOT = {{ has_tech = ac_land_{family}_2006 }}')+block('modifier','factor = 0\ndate < "2006.1.1"')
        body='category = land\navailable_for = {}\n'+block('roles',role)+block('priority',priority)
        for tier,year in enumerate(YEARS):
            design=block('priority',f'factor = {10+tier*10}')
            design+=block('enable',f'has_dlc = "No Step Back"\nhas_tech = ac_land_{family}_{year}\ndate > "{year-1}.12.31"')
            design+='history = yes\n'+block('target_variant',f'match_value = {4000+tier*100}\ntype = {chassis_id(family,year)}\n'+block('modules',fields(recipe(family,year))))
            design+=block('allowed_modules',items(recipe(family,year).values()))
            body+=block(f'ac_land_{family}_design_{year}',design)
        text+=block('ac_land_'+family+'_designs',body)
    return text


def target_requirements():
    return 'date > "2005.12.31"\n'+''.join('has_tech = '+ident+'\n' for ident in AI_TARGET_TECHS)+'num_of_military_factories > 12\n'+block('has_equipment','\n'.join(f'{ident} > {minimum-1}' for ident,minimum in AI_TARGET_STOCKS.items()))


def ai_output():
    research='name = ac_land_research_name\ndesc = ac_land_research_desc\nallowed = { always = yes }\nenable = { date > "2005.12.31" }\nabort_when_not_enabled = yes\n'
    research+=block('research','ac_land_category = 15\n')+'weight = { factor = 1 }\n'
    strategies=''
    for family,typ in [('infantry','infantry'),('mobility','motorized'),('mbt','armor'),('support','support'),('logistics','motorized')]:
        body='allowed = { always = yes }\n'+block('enable',f'has_tech = ac_land_{family}_2006\ndate > "2005.12.31"')+'abort_when_not_enabled = yes\n'
        body+=block('ai_strategy',f'type = equipment_production_factor\nid = {typ}\nvalue = 5')
        strategies+=block('ac_land_'+family+'_replacement',body)
    for family,archetype,threshold in [('surveillance','ac_land_sensor_equipment',100),('electronic_support','ac_land_electronic_equipment',120)]:
        enable=f'date > "2005.12.31"\nhas_tech = ac_land_{family}_2006\nnum_of_military_factories > 12\n'+block('has_equipment',archetype+' < '+str(threshold+1))
        body='allowed = { always = yes }\n'+block('enable',enable)+'abort_when_not_enabled = yes\n'
        body+=block('ai_strategy',f'type = equipment_production_min_factories_archetype\nid = {archetype}\nvalue = 1')
        strategies+=block('ac_land_'+family+'_manufactured_buffer',body)
    eligible=target_requirements()
    strategies+=block('ac_land_supplied_specialist_role','allowed = { always = yes }\n'+block('enable',eligible)+'abort_when_not_enabled = yes\n'+block('ai_strategy','type = role_ratio\nid = ac_land_tactical_support\nvalue = 5'))
    return block('ac_land_research',research),NOTE+strategies


def ai_template_output():
    eligible=target_requirements()
    target=block('upgrade_prio','factor = 1')+block('enable',eligible)+block('can_upgrade_in_field',eligible)
    target+=block('target_template',block('regiments','infantry = 6')+block('support','engineer = 1\nlogistics_company = 1\nac_land_surveillance_company = 1\nac_land_electronic_support_company = 1'))
    body='available_for = {}\nrole = ac_land_tactical_support\n'+block('upgrade_prio','factor = 1\n'+block('modifier','factor = 0\ndate < "2006.1.1"'))+block('ac_land_supplied_target',target)
    return NOTE+block('ac_land_supplied_support',body)


