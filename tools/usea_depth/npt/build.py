CHRON = c.CHRONICLE


class Keys(dict):
    """Localisation keys share one namespace across focuses, ideas, flags and events: never overwrite."""

    def __setitem__(self, key, value):
        if key in self:
            raise ValueError("Localisation key defined twice: " + key)
        super().__setitem__(key, value)


def outputs():
    loc = Keys()
    focus_file, ids = focuses()
    out = {
        "mod/2985041246/common/national_focus/ac_ud_npt.txt": focus_file,
        "mod/2985041246/events/ac_ud_npt.txt": events(loc),
        "mod/2985041246/common/ideas/ac_ud_npt.txt": ideas(loc),
        "mod/2985041246/common/characters/ac_ud_npt.txt": offices(loc),
        "mod/2985041246/common/scripted_effects/ac_ud_npt.txt": effects(),
        "mod/2985041246/interface/ac_ud_npt.gfx": sprites(),
        "tools/usea_depth/npt/budget.json": budget(ids),
        "docs/usea_depth/NPT.md": ledger(ids),
    }
    scripts = "\n".join(v for k, v in out.items() if k.endswith(".txt"))
    out["mod/2985041246/localisation/english/ac_ud_npt_l_english.yml"] = localisation(loc, scripts)
    return out, ids


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    out, ids = outputs()
    failures = []
    for relative, text in out.items():
        data = text.encode("utf-8-sig" if relative.endswith(".yml") else "utf-8")
        target = ROOT / relative
        if args.check:
            if not target.exists() or target.read_bytes().replace(b"\r\n", b"\n") != data:
                failures.append(relative)
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
    matched = seams.attach_file(seams.FOCUS / "NPT.txt", c.MARKER, ids, check=args.check)
    if args.check and not matched:
        failures.append("mod/2985041246/common/national_focus/NPT.txt (marker block)")
    _, art = build_art.build(args.check)
    failures.extend(art)
    if failures:
        raise SystemExit("North Point Usea Depth outputs differ: " + ", ".join(failures))
    print("North Point Usea Depth: %d focuses, %d events, %d ideas, %d files %s."
          % (len(ids), len(n.EVENTS), len(c.IDEAS), len(out), "checked" if args.check else "written"))
    if not args.check and not matched:
        print("NPT.txt changed: run python -B tools/usea_expansion/build_content.py")


if __name__ == "__main__":
    main()
