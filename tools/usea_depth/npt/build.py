HEADER = "# Generated by tools/usea_depth/npt/build.py. Usea Depth: North Point. Provisional gameplay unless a row in docs/usea_depth/NPT.md says otherwise.\n"
# Option keys skip d and t, which are the description and title suffixes.
LETTERS = "abcefghijk"


def block(key, body):
    lines = [line for line in body.split("\n")]
    return key + " = {\n" + "".join(("\t" + line if line.strip() else "") + "\n" for line in lines) + "}\n"


def number(value):
    return format(value, "g")


def picture(idea):
    return "ac_ud_npt_" + idea.ident[len("NPT_ud_"):]


def focus_text(f):
    ident = c.ident(f.slug)
    body = ["id = " + ident, "icon = GFX_ac_ud_focus_" + ident, "cost = %d" % f.cost, "x = %d" % f.x, "y = %d" % f.y]
    for group in f.pre:
        body.append("prerequisite = { " + " ".join("focus = " + c.ident(r) for r in group) + " }")
    if f.excl:
        body.append("mutually_exclusive = { " + " ".join("focus = " + c.ident(r) for r in f.excl) + " }")
    if f.available:
        body.append("available = { " + f.available + " }")
    body.append(block("ai_will_do", f.ai).rstrip("\n"))
    body.append(block("completion_reward", f.reward).rstrip("\n"))
    body.append("search_filters = { }")
    return block("shared_focus", "\n".join(body))


def focuses():
    ids = [c.ident(f.slug) for f in c.FOCUSES]
    return HEADER + "# Imported by npt_pre_continental_war_focus through the USEA DEPTH NORTH POINT marker block in NPT.txt.\n" \
        + "# Government changes happen only in ac_ud_npt_regime_*; every focus that reaches one has ai_will_do factor 0.\n\n" \
        + "\n".join(focus_text(f) for f in c.FOCUSES), ids


def event_key(number_, suffix=""):
    return "%s.%d%s" % (c.NAMESPACE, number_, suffix)


def events(loc):
    out = [HEADER, "add_namespace = " + c.NAMESPACE + "\n"]
    for number_, e in sorted(n.EVENTS.items()):
        key = event_key(number_)
        loc[key + ".t"] = e.title
        loc[key + ".d"] = seams.event_text(e.paragraphs, e.layer, e.cite)
        assert len(e.options) <= len(LETTERS), key
        body = ["id = " + key, "title = " + key + ".t", "desc = " + key + ".d",
                "picture = GFX_ac_ud_npt_event_" + e.picture, "is_triggered_only = yes", "trigger = { original_tag = NPT }"]
        for i, option in enumerate(e.options):
            name = key + "." + LETTERS[i]
            assert name not in loc, name
            loc[name] = option.label
            lines = ["name = " + name]
            if option.trigger:
                lines.append("trigger = { " + option.trigger + " }")
            lines.append("ai_chance = { factor = %d }" % option.ai)
            lines.extend(option.effect.split("\n"))
            body.append(block("option", "\n".join(lines)).rstrip("\n"))
        out.append(block("country_event", "\n".join(body)))
    return "\n".join(out)


def ideas(loc):
    rows = []
    for idea in c.IDEAS:
        loc[idea.ident] = idea.title
        loc[idea.ident + "_desc"] = idea.desc + "\n\n" + c.PROV
        modifier = "\n".join("%s = %s" % (k, number(v)) for k, v in idea.modifiers.items())
        rows.append(block(idea.ident, "picture = " + picture(idea) + "\nallowed = { always = no }\n"
                          "allowed_civil_war = { always = no }\nremoval_cost = -1\n" + block("modifier", modifier).rstrip("\n")))
    return HEADER + block("ideas", block("country", "\n".join(rows)).rstrip("\n"))


def offices(loc):
    bodies = []
    for office in c.OFFICES:
        ident, body = seams.office_character(c.TAG, office.slug, office.sub_ideology,
                                             "GFX_ac_ud_npt_portrait_" + office.slug)
        loc[ident] = office.title
        loc[ident + "_desc"] = office.desc
        bodies.append(body)
    return HEADER + "characters = {\n" + "".join(bodies) + "}\n"


def effects():
    rows = [block(name, body) for name, body in c.EFFECTS.items()]
    for slug, party, office, sub, elections, popularity in c.REGIMES:
        _, text = seams.regime_effect(c.PACKAGE, slug, party, "NPT_ud_%s_office" % office, sub, elections, popularity)
        rows.append(text)
    return HEADER + "\n".join(rows)


def sprites():
    lines = []
    for f in c.FOCUSES:
        lines.extend(seams.focus_sprites(c.PACKAGE, c.ident(f.slug)))
    for idea in c.IDEAS:
        lines.append('spriteType = { name = "GFX_idea_%s" texturefile = "%s/ideas/%s.dds" }' % (picture(idea), build_art.GFX, idea.ident))
    for office in c.OFFICES:
        lines.append('spriteType = { name = "GFX_ac_ud_npt_portrait_%s" texturefile = "%s/portraits/NPT_ud_%s_office.dds" }'
                     % (office.slug, build_art.GFX, office.slug))
    for scene in n.PICTURES:
        lines.append('spriteType = { name = "GFX_ac_ud_npt_event_%s" texturefile = "%s/events/%s.dds" }' % (scene, build_art.GFX, scene))
    return "spriteTypes = {\n" + "".join("\t" + line + "\n" for line in lines) + "}\n"


def existing_keys():
    keys = set()
    for path in (MOD / "localisation/english").rglob("*.yml"):
        if path.name != "ac_ud_npt_l_english.yml":
            keys.update(re.findall(r'^\s*([\w.]+):\d*\s+"', path.read_text(encoding="utf-8-sig"), re.M))
    return keys


def localisation(loc, text):
    for f in c.FOCUSES:
        ident = c.ident(f.slug)
        footer = c.MOD if f.layer == "mod" else c.OFF(f.cite) if f.layer == "official" else c.PROV
        assert ident not in loc and ident + "_desc" not in loc, ident
        loc[ident] = f.title
        loc[ident + "_desc"] = "\n\n".join(f.desc) + "\n\n" + footer
    known = existing_keys()
    for flag in sorted(set(re.findall(r"\bhas_(?:country|global)_flag\s*=\s*(\w+)", text))
                       | set(re.findall(r"\bset_country_flag\s*=\s*(\w+)", text)) | {"NPT_ud_shelter_readiness"}):
        if flag in c.LABELS and flag not in known:
            loc[flag] = c.LABELS[flag]

    def escape(value):
        return value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return "l_english:\n" + "".join(' %s:0 "%s"\n' % (k, escape(v)) for k, v in loc.items())


def budget(ids):
    return json.dumps({"package": c.PACKAGE, "marker": c.MARKER, "focuses": {c.TAG: len(ids)},
                       "trees": {c.TREE: len(ids)}, "events": len(n.EVENTS)}, indent=2) + "\n"


