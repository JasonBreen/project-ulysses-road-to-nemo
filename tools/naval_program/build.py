from script import parse,get,render
from naval_content import YEARS,MTG,FAMILIES,FAMILY,SHIPS,TECHS,MODULES,tech_id,model_id,hull_id,module_id,recipe,dependencies,unlocks
from naval_primary import Primary,STATS

NOTE='# Generated by tools/naval_program/build.py. New names, dates and statistics are provisional gameplay.\n'
def block(key,s):return key+' = {\n'+'\n'.join('\t'+v for v in s.splitlines())+'\n}\n'
def number(v):return format(v,'.9g') if isinstance(v,float) else str(v)
def fields(row):return '\n'.join(k+' = '+number(v) for k,v in row.items())+'\n'
def values(kind,tier,field='add'):
    row=MODULES[kind];steps=row.get('step' if field=='add' else field+'_step',{})
    return {k:round(v+tier*steps.get(k,0),7) for k,v in row.get(field,{}).items()}

def modules():
    rows=NOTE
    for kind,row in MODULES.items():
        for tier,year in enumerate(YEARS):
            s=f'category = {row["category"]}\nabbreviation = "N{tier+1}"\nxp_cost = 3\ndismantle_cost_ic = 50\n'
            if tier:s+='parent = '+module_id(kind,YEARS[tier-1])+'\n'
            if row.get('equipment_type'):s+='add_equipment_type = '+row['equipment_type']+'\n'
            if row.get('crew'):s+='manpower = '+str(row['crew']+tier*row.get('crew_step',0))+'\n'
            for source,target in [('add','add_stats'),('average','add_average_stats'),('multiply','multiply_stats')]:
                if values(kind,tier,source):s+=block(target,fields(values(kind,tier,source)))
            s+=block('build_cost_resources',fields(row['resources']))
            rows+=block(module_id(kind,year),s)
    return block('equipment_modules',rows)

def base_stats(family,tier):
    row=dict.fromkeys(STATS,0)
    costs={'escort':1200,'cruiser':2600,'fleet':3400,'submarine':1200,'carrier':7000}
    crew={'escort':240,'cruiser':850,'fleet':1100,'submarine':100,'carrier':1800}
    row.update(build_cost_ic=costs[family]*(1+.12*tier),manpower=crew[family],reliability=.88+.015*tier,
        naval_speed=(20 if family=='submarine' else 27 if family=='carrier' else 28)+tier,
        naval_range=(4000 if family in ('escort','submarine') else 6500)+tier*500,
        max_strength={'escort':70,'cruiser':170,'fleet':230,'submarine':45,'carrier':380}[family]*(1+.1*tier),
        surface_detection=25+3*tier,sub_detection=0,sub_visibility=18-2*tier if family=='submarine' else 0,
        surface_visibility={'escort':8,'cruiser':13,'fleet':15,'submarine':1,'carrier':28}[family],
        naval_dominance_factor={'escort':35,'cruiser':160,'fleet':200,'submarine':20,'carrier':400}[family],naval_weather_penalty_factor=1)
    return row
def resources(family):return {'steel':5,'chromium':2} if family=='carrier' else {'steel':3,'chromium':1} if family in ('cruiser','fleet') else {'steel':2}

def equipment(contract):
    rows=NOTE
    for family in SHIPS:
        slots=contract['families'][family.id]['slots']
        for tier,year in enumerate(YEARS):
            selected={k:'empty' for k in slots};selected.update(recipe(family.id,year))
            for modular in (False,True):
                ident=hull_id(family.id,year) if modular else model_id(family.id,year)
                parent=(hull_id(family.id,YEARS[tier-1]) if modular else model_id(family.id,YEARS[tier-1])) if tier else (family.hull_parent if modular else family.parent)
                shiptype='screen_ship' if modular and family.id=='fleet' else family.equipment_type
                s=f'year = {year}\nactive = no\nis_buildable = {"no" if modular else "yes"}\npriority = {3100+10*tier}\narchetype = {family.archetype}\nparent = {parent}\ntype = {shiptype}\npicture = {ident}\n'
                s+=('module_slots = inherit\n' if modular else block('module_slots',render([[k,'=',v] for k,v in slots.items()])))
                s+=block('can_be_produced','has_dlc = "Man the Guns"' if modular else 'NOT = { has_dlc = "Man the Guns" }')
                if modular:s+='derived_variant_name = '+ident+'\n'
                bare=base_stats(family.id,tier);bare.pop('naval_torpedo_hit_chance_factor') # Native module add_stats supplies this coefficient.
                s+=fields(bare)+block('resources',fields(resources(family.id)))+block('default_modules',fields(selected))
                # Explicit same bare hull + explicit same recipe on both native
                # routes. Contributions are never baked into this hull body.
                rows+=block(ident,s)
    return block('equipments',rows)

def technologies():
    rows=NOTE
    for row in TECHS:
        family=row['family'];tier=row['tier'];year=row['year'];required=dependencies(family,tier)
        s=f'start_year = {year}\nresearch_cost = {2.5+.3*tier:g}\n'
        gate=f'date > "{year-1}.12.31"\n'+''.join('has_tech = '+v+'\n' for v in required)
        if family!='systems' and tier==0:
            f=FAMILY[family]
            gate+=block('OR',block('AND','NOT = { has_dlc = "Man the Guns" }\nhas_tech = '+f.legacy_foundation)+block('AND','has_dlc = "Man the Guns"\nhas_tech = '+f.designer_foundation))
        s+=block('allow',gate)+block('dependencies','\n'.join(v+' = 1' for v in required))
        s+=block('folder',f'name = ac_naval_folder\nposition = {{ x = {tier*4} y = 0 }}')
        s+=block('categories','ac_naval_category\nac_naval_'+family+'_category\nnaval_equipment')
        if tier<3:s+=block('path',f'leads_to_tech = {tech_id(family,YEARS[tier+1])}\nresearch_cost_coeff = 1')
        if family!='systems':s+=block('enable_equipments',model_id(family,year)+'\n'+hull_id(family,year))
        s+=block('enable_equipment_modules','\n'.join(unlocks(family,year)))
        s+=block('ai_will_do','factor = 5\n'+block('modifier','factor = 0\ndate < "'+str(year)+'.1.1"'))
        rows+=block(row['id'],s)
    return block('technologies',rows)

def ai():
    roles={'escort':'naval_escort','cruiser':'naval_cruiser_light','fleet':'naval_cruiser_heavy','submarine':'naval_submarine','carrier':'naval_carrier'}
    designs=NOTE;priorities=NOTE
    for f in SHIPS:
        priority='factor = 6000\n'+block('modifier','factor = 0\n'+block('OR','date < "2006.1.1"\nNOT = { has_tech = '+tech_id(f.id,2006)+' }\nNOT = { has_dlc = "Man the Guns" }'))
        s='category = naval\navailable_for = {}\n'+block('roles',roles[f.id])+block('priority',priority)
        for tier,year in enumerate(YEARS):
            gate=f'date > "{year-1}.12.31"\nhas_dlc = "Man the Guns"\nhas_tech = {tech_id(f.id,year)}\nhas_tech = {tech_id("systems",year)}\n'
            d=block('priority',f'factor = {10+tier*10}')+block('enable',gate)+'history = yes\n'
            d+=block('target_variant',f'match_value = {5000+tier*100}\ntype = {hull_id(f.id,year)}\n'+block('modules',fields(recipe(f.id,year))))
            d+=block('allowed_modules','\n'.join(recipe(f.id,year).values()));s+=block(tech_id(f.id,year)+'_design',d)
        designs+=block('ac_naval_'+f.id+'_designs',s)
        # role_ratio is a weighting, not a free hull, new yard, queue guarantee
        # or assertion that a small state should build a carrier.
        gate=f'date > "2005.12.31"\nhas_tech = {tech_id(f.id,2006)}\nnum_of_naval_factories > '+('9' if f.id=='carrier' else '2')
        priorities+=block('ac_naval_'+f.id+'_replacement','allowed = { always = yes }\n'+block('enable',gate)+'abort_when_not_enabled = yes\n'+block('ai_strategy',f'type = role_ratio\nid = {roles[f.id]}\nvalue = 5'))
    plan=block('ac_naval_research','name = ac_naval_research_name\ndesc = ac_naval_research_desc\nallowed = { always = yes }\nenable = { date > "2005.12.31" }\nabort_when_not_enabled = yes\nresearch = { ac_naval_category = 15 }\nweight = { factor = 1 }')
    return designs,priorities,NOTE+plan

def localization():
    values={'ac_naval_folder':'Naval Systems','ac_naval_folder_desc':'Conventional naval manufacturing, 2006–2020. Research and build the eligible ship and components.',
        'ac_naval_tab_short':'NAVAL','ac_naval_page_heading':'NAVAL SYSTEMS / SUSTAINED FLEET CAPABILITY',
        'ac_naval_page_scope':'2006–2020 conventional ships and components. Aircraft, crews, dockyards and supplies remain separate requirements.',
        'ac_naval_research_name':'Naval Service Capability','ac_naval_research_desc':'Research and manufacture conventional ships with dockyard capacity, materials, trained crews, fuel and repair support.',
        'ac_naval_category':'Modern Conventional Naval Systems'}
    for f in FAMILIES:
        values['ac_naval_label_'+f.id]=f.title;values['ac_naval_'+f.id+'_category']=f.title
        for y in YEARS:
            ident=tech_id(f.id,y);values[ident]=f.title+' '+str(y);values[ident+'_desc']=f.description
            if f.id=='systems':continue
            for ident,suffix in ((model_id(f.id,y),''),(hull_id(f.id,y),' Hull')):
                values[ident]=f.model+suffix+' '+str(y);values[ident+'_short']=f.model+' '+str(y)[2:];values[ident+'_desc']=f.description
    for kind,row in MODULES.items():
        for y in YEARS:
            ident=module_id(kind,y);values[ident]=row['title']+' '+str(y)
            values[ident+'_desc']='A researched '+row['title'].lower()+' and its service fittings, requiring manufactured components, materials, installation and trained crews.'
    return '\ufeffl_english:\n'+'\n'.join(' '+k+':0 "'+v+'"' for k,v in values.items())+'\n'

def outputs():
    contract=json.loads((HERE/'primary_contract.json').read_text());designs,strategies,plan=ai()
    return {'common/technologies/ac_naval_program.txt':technologies(),'common/units/equipment/zz_ac_naval_equipment.txt':equipment(contract),
        'common/units/equipment/modules/zz_ac_naval_modules.txt':modules(),'common/ai_equipment/ac_naval_designs.txt':designs,
        'common/ai_strategy/ac_naval_replacements.txt':strategies,'common/ai_strategy_plans/ac_naval_research.txt':plan,
        'common/technology_tags/ac_naval_categories.txt':NOTE+block('technology_categories','ac_naval_category\n'+'\n'.join('ac_naval_'+f.id+'_category' for f in FAMILIES))+block('technology_folders','ac_naval_folder = { ledger = navy }'),
        'localisation/english/ac_naval_program_l_english.yml':localization()}

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
    for name,value in outputs().items():
        if not name.endswith('.yml'):parse(value)
        path=MOD/name;raw=value.encode()
        if a.check:
            if not path.exists() or path.read_bytes().replace(b'\r\n',b'\n')!=raw:raise SystemExit('Stale naval output: '+name)
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(raw)
    print('NAVAL 24 nodes / 40 models / 64 modules: '+('consistent' if a.check else 'generated'))
