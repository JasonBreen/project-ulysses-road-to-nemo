"""Original Sotoan campaign briefs. None of these 1991 dilemmas are canon.

Each row is a specific problem and three alternative programmes. Every
programme has three authored focuses; together with its opening this is ten.
Names identify original recurring staff, not historical officeholders.
"""
from dataclasses import dataclass


@dataclass(frozen=True)
class Programme:
    slug: str
    domain: str
    title: str
    problem: str
    paths: tuple


def chapter(slug, domain, title, problem, *paths):
    return Programme(slug, domain, title, problem, tuple(tuple(p.split('|')) for p in paths))


