def yml(value):
    return value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def flags_in(text):
    return set(re.findall(r"\b(?:set_country_flag|has_country_flag|clr_country_flag)\s*=\s*(ERU_ud_\w+)", text))


def localisation(script):
    rows = OrderedDict()

    def put(key, value):
        if key in rows:
            raise ValueError("Duplicate Erusea localisation key: " + key)
        if any(ord(c) > 126 for c in value):
            raise ValueError("Non-ASCII text in " + key)
        rows[key] = value

    for row in C.FOCUSES:
        put(row.id, row.title)
        put(row.id + "_desc", row.desc)
    for ident, (title, desc, _, _) in C.IDEAS.items():
        put(ident, title)
        put(ident + "_desc", desc)
    for number, event in sorted(N.EVENTS.items()):
        ident = "%s.%d" % (C.NAMESPACE, number)
        put(ident + ".t", event["title"])
        put(ident + ".d", seams.event_text(event["paragraphs"], event["layer"], event["citation"]))
        for index, (label, _, _) in enumerate(event["options"]):
            put("%s.%s" % (ident, option_letter(index)), label)
    for ident, _, title, desc, _ in offices().values():
        put(ident, title)
        put(ident + "_desc", desc)
    titles = {row.id: row.title for row in C.FOCUSES}
    for name in sorted(flags_in(script)):
        if name.endswith("_done") and name[:-5] in titles:
            put(name, "Completed: " + titles[name[:-5]])
        elif name in FLAG_LABELS:
            put(name, FLAG_LABELS[name])
        else:
            raise ValueError("Package flag without a readable label: " + name)
    body = "l_english:\n" + "".join(' %s:0 "%s"\n' % (key, yml(value)) for key, value in rows.items())
    return "\ufeff" + body


