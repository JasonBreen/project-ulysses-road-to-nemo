def flags_used():
    text = "\n".join([focus_file(), event_file(), effects_file()])
    return sorted(set(re.findall(r"(?:has|set|clr)_country_flag = (\w+)", text)) | set(re.findall(r"has_global_flag = (\w+)", text)))


def existing_keys():
    keys = set()
    for path in (MOD / "localisation/english").rglob("*.yml"):
        if path.name == "ac_ud_fcu_l_english.yml":
            continue
        keys.update(re.findall(r"(?m)^\s*([\w.]+):\d*\s", path.read_text(encoding="utf-8-sig", errors="replace")))
    return keys


def flag_label(flag):
    if flag in C.FLAG_LABELS:
        return C.FLAG_LABELS[flag]
    if flag.endswith("_done") and flag[:-5] in FOCUS:
        return "Completed: " + FOCUS[flag[:-5]].title
    setters = [f for f in C.FOCUSES if re.search(r"set_country_flag = %s\b" % flag, f.reward)]
    if setters:
        return "Recorded: " + setters[0].title
    raise SystemExit("No label for flag " + flag)


def body_text(paragraphs, layer, cite):
    return seams.event_text(paragraphs, layer, cite)


def localisation():
    rows = []
    for f in C.FOCUSES:
        rows.append((f.id, f.title))
        rows.append((f.id + "_desc", f.desc + "\n\n" + layer_line(f)))
    for ident, name, desc, _, _ in C.IDEAS:
        rows.append((ident, name))
        rows.append((ident + "_desc", desc))
    for number, e in sorted(N.EVENTS.items()):
        rows.append((e["id"] + ".t", e["title"]))
        if e["variants"]:
            for index, (_, paragraphs) in enumerate(e["variants"]):
                rows.append(("%s.d.%s" % (e["id"], "abc"[index]), body_text(paragraphs, e["layer"], e["cite"])))
        else:
            rows.append((e["id"] + ".d", body_text(e["paragraphs"], e["layer"], e["cite"])))
        for suffix, text, _, _ in e["options"]:
            rows.append(("%s.%s" % (e["id"], suffix), text))
    taken = existing_keys()
    for flag in flags_used():
        if flag not in taken:
            rows.append((flag, flag_label(flag)))
    for key, value in list(C.VARIABLE_LABELS.items()) + list(C.TOOLTIPS.items()):
        rows.append((key, value))
    for slug, (_, name, desc) in OFFICES.items():
        ident = "FCU_ud_%s_office" % slug
        rows += [(ident, name), (ident + "_desc", desc)]
    keys = [k for k, _ in rows]
    duplicates = sorted({k for k in keys if keys.count(k) > 1})
    if duplicates:
        raise SystemExit("Duplicate localisation keys: " + ", ".join(duplicates))
    clash = sorted(set(keys) & taken)
    if clash:
        raise SystemExit("Localisation keys already defined elsewhere: " + ", ".join(clash))
    return "l_english:\n" + "".join(' %s:0 "%s"\n' % (k, esc(v)) for k, v in rows)


