"""Own compact project/garrison rows; preserve every unrelated GFX byte."""
import argparse
import hashlib
import io
import json
from pathlib import Path
import re

from PIL import __version__ as PILLOW,Image,ImageOps
from geometry import row_icon

HERE=Path(__file__).resolve().parent;ROOT=HERE.parents[1];MOD=ROOT/'mod/2985041246'
PROJECTS=('excalibur','v2','stonehenge','arkbird','megalith','rhongomyniad')
GARRISONS=('none','low','mid','big')


def outputs():
    if PILLOW!='11.3.0':raise ValueError('Use CI-pinned Pillow11.3.0 for reproducible DDS')
    out={};assets=[]
    jobs=[('project_'+x,x,'GFX_decision_ac_sp_'+x,'interface/ac_special_projects.gfx') for x in PROJECTS]
    jobs += [('garrison_'+x,'garrison_'+x,'GFX_decision_BLK_garrison_control_'+x,'interface/ac_decisions.gfx') for x in GARRISONS]
    before=json.loads((HERE/'source/before_bindings.json').read_text())['bindings']
    gfx={key:(HERE/'source'/source).read_text(encoding='utf-8-sig') for key,source in [('interface/ac_special_projects.gfx','project_gfx_before.gfx'),('interface/ac_decisions.gfx','legacy_gfx_before.gfx')]}
    for name,subject,sprite,binding in jobs:
        im=row_icon(subject);flag_metadata={}
        if subject.startswith('garrison_'):
            flag=MOD/'gfx/flags/BLK.tga'
            with Image.open(flag) as source:stamp=ImageOps.contain(source.convert('RGBA'),(13,6),Image.Resampling.LANCZOS)
            im.alpha_composite(stamp,((26-stamp.width)//2,5))
            flag_metadata=dict(flag='gfx/flags/BLK.tga',flag_sha256=hashlib.sha256(flag.read_bytes()).hexdigest())
        stream=io.BytesIO();im.save(stream,format='DDS');raw=stream.getvalue()
        relative='gfx/interface/ac_decision_rows/'+name+'.dds';out[MOD/relative]=raw
        pattern=r'(name\s*=\s*"'+re.escape(sprite)+r'"\s*\n\s*texturefile\s*=\s*)"'+re.escape(before[sprite]['texture'])+'"'
        gfx[binding],count=re.subn(pattern,lambda m:m[1]+'"'+relative+'"',gfx[binding])
        if count!=1:raise ValueError('Missing or repeated captured row binding: '+sprite)
        assets.append(dict(file=relative,width=26,height=29,frame_width=26,frames=1,alpha_min=im.getchannel('A').getextrema()[0],alpha_max=im.getchannel('A').getextrema()[1],
            format='DDS RGBA8',sha256=hashlib.sha256(raw).hexdigest(),sprite=sprite,binding=binding,subject=subject,
            provenance='Original compact row geometry; garrison rows retain the existing BLK flag identity; no installed/external pixels',source='tools/decision_row_art/geometry.py',**flag_metadata,
            source_sha256=hashlib.sha256((HERE/'geometry.py').read_bytes().replace(b'\r\n',b'\n')).hexdigest()))
    gfx['interface/ac_special_projects.gfx']=gfx['interface/ac_special_projects.gfx'].replace(
        '# Project Ulysses special-project placeholder art. Every sprite reuses a\n# mod-owned texture in gfx/interface/ac_briefing; no vanilla textures.',
        '# Project Ulysses special-project presentation.\n# Large placeholder assets retain their original mod-owned sources.\n# Compact row artwork is generated by tools/decision_row_art/build.py.')
    for binding,text in gfx.items():out[MOD/binding]=text.encode('utf-8')
    out[HERE/'assets.json']=(json.dumps(assets,indent=2)+'\n').encode()
    loc=['\ufeffl_english:']
    for region in ('Hugelse','Hoffnung','Friede'):
        ident='BLK_expand_influence_in_the_'+region.lower()+'_garrison'
        loc.append(f' {ident}:0 "Expand Influence in the {region} Garrison"')
        loc.append(f' {ident}_desc:0 "Commit 25 political power to a 14-day campaign to expand influence in the {region} garrison. The action raises local control by one level, up to three, and occupies the shared garrison-campaign slot while active."')
    loc+=[' BLK_expand_influence_trigger_tt:0 "Garrison control is below its maximum."',
          ' BLK_expand_influence_nationalists_tt:0 "Increase local garrison control by one level, up to three."']
    out[MOD/'localisation/english/ac_garrison_rows_l_english.yml']=('\n'.join(loc)+'\n').encode('utf-8')
    return out


if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for path,data in outputs().items():
        if args.check:
            old=path.read_bytes() if path.exists() else b''
            if path.suffix in ('.json','.gfx'):old=old.replace(b'\r\n',b'\n')
            if old!=data:raise SystemExit('Stale compact row art: '+str(path.relative_to(ROOT)))
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(data)
    print('Compact project/garrison art:10 original DDS / stable row bindings '+('consistent' if args.check else 'packaged'))
