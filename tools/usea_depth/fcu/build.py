def block(key, body, depth=0):
    tab = "\t" * depth
    lines = [tab + "\t" + line if line.strip() else "" for line in body.splitlines()]
    return tab + key + " = {\n" + "\n".join(lines) + "\n" + tab + "}\n"


def esc(text):
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


