def block(key, body):
    lines = body.strip("\n").split("\n") if body.strip() else []
    return key + " = {\n" + "".join("\t" + line + "\n" if line.strip() else "\n" for line in lines) + "}\n"


def resolve(name):
    return name if name.startswith("ERU_") else "ERU_ud_" + name


def gate(row):
    if row.tree == "opening":
        parts = [C.OPENING_GATE, C.BANDS[row.band][0] if row.band else "", row.gate]
    else:
        parts = [C.WAR_GATE, row.gate]
    return " ".join(p for p in parts if p)


def exclusions():
    table = {row.id: set() for row in C.FOCUSES}
    for row in C.FOCUSES:
        for other in row.excl:
            table[row.id].add(resolve(other))
            table[resolve(other)].add(row.id)
    return table


def focus_text(row, excl):
    condition = gate(row)
    reward = row.reward.replace("{id}", row.id)
    if row.event:
        reward += "\ncountry_event = { id = %s.%d }" % (C.NAMESPACE, row.event)
    guarded = block("if", "limit = { %s NOT = { has_country_flag = %s_done } }\nset_country_flag = %s_done\n%s" % (condition, row.id, row.id, reward))
    body = ["id = " + row.id, "icon = GFX_ac_ud_focus_" + row.id, "x = %d" % row.x, "y = %d" % row.y, "cost = %d" % row.cost]
    for group in row.pre:
        body.append("prerequisite = { %s }" % " ".join("focus = " + resolve(n) for n in group.split("|")))
    if excl:
        body.append("mutually_exclusive = { %s }" % " ".join("focus = " + i for i in sorted(excl)))
    body += ["available = { %s }" % condition, "cancel_if_invalid = yes", "continue_if_invalid = no",
             "ai_will_do = { factor = %d }" % row.ai, block("completion_reward", guarded).rstrip("\n"), "search_filters = { }"]
    return block("shared_focus", "\n".join(body))


def option_letter(index):
    return "abcdefgh"[index]


def events_text():
    parts = [HEADER, "add_namespace = %s\n" % C.NAMESPACE]
    for number, event in sorted(N.EVENTS.items()):
        ident = "%s.%d" % (C.NAMESPACE, number)
        body = ["id = " + ident, "title = %s.t" % ident, "desc = %s.d" % ident,
                "picture = GFX_ac_ud_eru_event_" + event["picture"], "is_triggered_only = yes", "fire_only_once = yes",
                "trigger = { original_tag = ERU }"]
        for index, (_, effect, factor) in enumerate(event["options"]):
            body.append(block("option", "name = %s.%s\nai_chance = { factor = %d }\n%s" % (ident, option_letter(index), factor, effect)).rstrip("\n"))
        parts.append(block("country_event", "\n".join(body)))
    return "\n".join(parts)


