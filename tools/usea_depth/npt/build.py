"""Generate the North Point Usea Depth package (focuses, events, ideas, effects, offices,
localisation, sprites, art, budget and ledger) and attach its NPT.txt import block.

    python -B tools/usea_depth/npt/build.py [--check]

--check compares every output (and the NPT.txt marker block) without writing.
After a real run that changed NPT.txt, re-run the owner generator:
    python -B tools/usea_expansion/build_content.py
"""
