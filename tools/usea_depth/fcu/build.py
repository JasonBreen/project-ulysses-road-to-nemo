def encode(path, text):
    data = text.encode("utf-8")
    return b"\xef\xbb\xbf" + data if path.endswith(".yml") else data


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    problems = validate()
    if problems:
        raise SystemExit("Central Usea content problems:\n- " + "\n- ".join(problems))
    stale = []
    for relative, text in outputs().items():
        path = ROOT / relative
        data = encode(relative, text)
        current = path.read_bytes() if path.exists() else None
        if current is None or current.replace(b"\r\n", b"\n") != data:
            stale.append(relative)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(data)
    opening = [f.id for f in C.FOCUSES if f.tree == C.OPENING]
    war = [f.id for f in C.FOCUSES if f.tree == C.WAR]
    for path, ids in ((OPENING_FILE, opening), (WAR_FILE, war)):
        if not seams.attach_file(path, MARKER, ids, check=args.check):
            stale.append(path.relative_to(ROOT).as_posix() + " (import block)")
    if args.check:
        if stale:
            raise SystemExit("Central Usea outputs are stale:\n- " + "\n- ".join(stale))
        print("Central Usea package: %d focuses, %d ideas, %d events; outputs match." % (len(C.FOCUSES), len(C.IDEAS), len(N.EVENTS)))
    else:
        print("Central Usea package: wrote %d outputs (%d focuses, %d ideas, %d events)." % (len(stale), len(C.FOCUSES), len(C.IDEAS), len(N.EVENTS)))
        if any("import block" in s for s in stale):
            print("Import blocks changed: re-run tools/usea_expansion/build_content.py and tools/build_continental_war.py.")


if __name__ == "__main__":
    main()
