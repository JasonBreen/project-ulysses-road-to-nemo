"""Render docs/usea_depth/MINORS_B.md from the state modules (generated; do not hand-edit)."""

SHARED = [
    ("docs/LORE_EVENT_COVERAGE_BACKLOG.md", "one coverage row"),
    ("tools/world_foundation/country_registry.json", "regenerated by tools/content_waves/refresh_records.py"),
    ("docs/evidence/event-style/*", "regenerated by tools/content_waves/refresh_records.py"),
    ("docs/evidence/decision-rows/*", "regenerated by tools/content_waves/refresh_records.py"),
]

PARTY = {"democratic": "Democratic", "communism": "Communist", "fascism": "Fascist", "neutrality": "Non-aligned", "monarchism": "Monarchist"}


def cell(text):
    return str(text).replace("|", "/").replace("\n", " ")


def render(states, event_ids, regime_name, office_id, tree_id, fid):
    lines = [
        "# Usea Depth: minors B ledger",
        "",
        "Generated by `python -B tools/usea_depth/minors_b/build.py`; do not edit by hand. "
        "Package contract: [README.md](README.md). Native status: not tested in HOI4. Native acceptance remains under #8.",
        "",
        "Package `minors_b` gives Spayca, Calladen, Roca Roja, Rohden, Voslage and Corscae their own national trees, "
        "and Shilage a short release tree. They replace the shared 36-focus regional tree for these tags by weight "
        "(+45 against +5). Old saves switch through each country's \"Adopt\" decision, gated on `ac_pol_previous_tree_idle`.",
        "",
        "## Source rules",
        "",
        "- No official source describes any of these states. Every tree, event, idea, office and decision is "
        "**provisional gameplay**. Each state's provinces, resources, buildings, neighbours, ruling party and treaty-council "
        "membership are read from the mod's own history files and are **mod provenance**.",
        "- Official dates are used only as calendar gates and as reported news: ACES Chronicle 1996 / 04.20 (Ulysses "
        "announced), 1997 / 05.30 (Usea-wide coup), 1998 / 06.19 (Stonehenge completed), 1999 / 07.08 (impact), "
        "2000 / 04.21 (Erusean refugee closure) and the 2003-2005 war rows "
        "([Chronicle](https://acecombat.jp/en/chronicle/details/), as compiled in "
        "[USEAN_CONTINENTAL_WAR.md](../USEAN_CONTINENTAL_WAR.md)).",
        "- No new named people: every new government is an unnamed office card with a generated portrait. Chronicle people "
        "appear in text only. No Chronicle place is mapped to a state; Stonehenge = state 310 stays the only mapping.",
        "- The \"Central Usean Treaty Council\" is the mod's `CNEA_member_idea` membership (mod provenance: the history files of "
        "the members, and the `CNEA_parliament_decisions_category` label). This package never adds or removes that idea.",
        "- No `transfer_state`, cores, borders, wars, annexations or faction changes. No `ac_ucw_*` flag writes. Nothing reads or "
        "writes Erusea's grievance. The AI never takes a political path, so it keeps the 1991 governments.",
        "",
        "## Trees",
        "",
        "| Tag | Country | Tree | Focuses | Events | Political paths | Treaty council (CNEA) in 1991 | Mod states |",
        "| --- | --- | --- | ---: | ---: | --- | --- | --- |",
    ]
    for s in states:
        paths = ", ".join(r.office for r in s.REGIMES)
        lines.append("| %s | %s | `%s` | %d | %d | %s | %s | %s |" % (
            s.TAG, s.NAME, tree_id(s.TAG), len(s.FOCUSES), len(s.EVENTS), cell(paths),
            "member" if s.CNEA else "not a member", ", ".join(str(n) for n in s.STATES)))
    lines.append("| | **Total** | | **%d** | **%d** | | | |" % (sum(len(s.FOCUSES) for s in states), sum(len(s.EVENTS) for s in states)))
    lines += ["", "## Political paths", "",
              "Each path is one scripted effect built with `seams.regime_effect()`. Every focus that reaches one has "
              "`ai_will_do = { factor = 0 }`. Seeded popularities are placeholders set only by these effects.", "",
              "| Effect | Office card | Ruling party | Leader ideology | Elections | Seeded popularity | Layer |",
              "| --- | --- | --- | --- | --- | --- | --- |"]
    for s in states:
        for r in s.REGIMES:
            pops = ", ".join("%s %d" % (k, v) for k, v in sorted(r.popularities.items(), key=lambda kv: -kv[1]) if v)
            lines.append("| `%s` | `%s` (%s) | %s | %s | %s | %s | Provisional gameplay |" % (
                regime_name(s, r.slug), office_id(s, r), cell(r.office), PARTY[r.party], r.ideology,
                "allowed" if r.elections else "suspended", pops))
    lines += ["", "## Events", "", "Every event body is built with `seams.event_text()` and passes `seams.event_problems()`.", "",
              "| ID | Title | Fired by | Layer and citation |", "| --- | --- | --- | --- |"]
    for s in states:
        ids = event_ids(s)
        sources = {}
        for f in s.FOCUSES:
            for token in list(f.reward) + (["event:" + f.event] if f.event else []):
                if token.startswith("event:"):
                    sources.setdefault(token[6:], []).append("focus `%s`" % fid(s, f.slug))
        for e in s.EVENTS:
            for o in e.options:
                for token in o.effects:
                    if token.startswith("event:"):
                        sources.setdefault(token[6:], []).append("event `%s`" % ids[e.slug])
        for d in s.DECISIONS:
            for token in d.effects:
                if token.startswith("event:"):
                    sources.setdefault(token[6:], []).append("decision `%s`" % fid(s, d.slug))
        for e in s.EVENTS:
            lines.append("| `%s` | %s | %s | %s%s |" % (ids[e.slug], cell(e.title), ", ".join(sources.get(e.slug, [])),
                                                      e.layer, (": " + cell(e.citation)) if e.citation else ""))
    lines += ["", "## Lore, geography and design rows", "",
              "| Claim or identifier | Source layer | Citation or reference | Affected IDs | Status |", "| --- | --- | --- | --- | --- |"]
    for s in states:
        for row in s.LEDGER:
            lines.append("| %s | %s | %s | %s | %s |" % (cell(row.claim), row.layer, cell(row.citation), cell(row.ids), cell(row.status)))
    lines += ["", "## Shared files touched", "",
              "Every other file is new and owned by this package (see the README's ownership list).", ""]
    lines += ["- `%s`: %s" % row for row in SHARED]
    lines += ["", "## Checks", "",
              "- `python -B tools/usea_depth/minors_b/build.py --check` and `python -B tools/usea_depth/minors_b/build_art.py --check`",
              "- `python -B tools/usea_depth/minors_b/test_minors_b.py` (run by `tools/usea_depth/run_checks.py`)",
              "- All checks are static. No native HOI4 launch, parser, save/load, AI or long-run testing was performed.", ""]
    return "\n".join(lines)
