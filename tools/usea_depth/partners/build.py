"""Compile the Usea Depth partners package. --check never writes.

Writes the shared focus definitions, events, ideas, regime effects, office
leaders, localisation, sprite bindings, budget.json and this package's marker
block in the four partner trees (through seams.attach_file only). Textures are
packaged separately by build_art.py.

After attaching, re-run the partner owner generator so its own output keeps the
block ahead of the campaign imports:  cd tools/usean_partners && python -B build.py
"""
import argparse
import json
from pathlib import Path
import sys

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path[:0] = [str(HERE), str(ROOT / "tools")]

from usea_depth import seams  # noqa: E402
from content import (BUDGET, BY_ID, COUNTRIES, FOCUSES, GATE_TEXT, GATES, IDEAS, MARKER, NAMESPACE,  # noqa: E402
                     PACKAGE, PATH_FLAGS, REGIMES)
from narrative import all_events  # noqa: E402

MOD = ROOT / "mod/2985041246"
NOTE = "# Usea Depth partners: generated by tools/usea_depth/partners/build.py. Provisional gameplay unless a row cites the ACES Chronicle.\n"
PICTURES = ("politics", "warning", "coup", "desert", "impact", "refugees", "war", "peace", "yards", "depots", "records")
TECH_CATEGORIES = ("industry", "electronics", "construction_tech", "logistics_tech", "train_tech", "engineers_tech",
                   "radar_tech", "infantry_weapons", "land_doctrine")
# Every reward token build.py understands; anything else fails the build.
REWARD_TOKENS = ("axis", "prep", "idea", "drop", "tech", "xp", "stab", "ws", "event", "regime", "flag")


def block(key, body):
    lines = "\n".join("\t" + line if line else "" for line in body.splitlines())
    return key + " = {\n" + lines + "\n}\n"


def office(regime):
    row = REGIMES[regime]
    return "%s_ud_%s_office" % (row["tag"], row["office"])


def portrait(ident):
    return "GFX_ac_ud_portrait_" + ident


def event_id(n):
    return "%s.%d" % (NAMESPACE, n)


def compile_reward(tag, tokens, bonus_name):
    """Return (visible effect text, uses_programme) for reward tokens."""
    axes = COUNTRIES[tag]["axes"]
    lines, programme, prep, trailing = [], [], [], []
    for token in tokens:
        if ":" in token:
            kind, value = token.split(":", 1)
        else:
            kind = next((name for name in ("stab", "ws", "prep") if token.startswith(name)), token)
            value = token[len(kind):]
        if kind not in REWARD_TOKENS:
            raise ValueError("Unknown reward token: " + token)
        if kind == "axis":
            axis, amount = value.split("+")
            if axis not in axes:
                raise ValueError("%s has no programme axis %s" % (tag, axis))
            programme.append("add_to_variable = { ac_up_%s_%s = %d }" % (tag.lower(), axis, int(amount)))
        elif kind == "prep":
            prep.append("add_to_variable = { ac_up_preparedness = %d }" % int(value.lstrip("+")))
        elif kind == "idea":
            if value not in IDEAS or not value.startswith(tag + "_ud_"):
                raise ValueError("Unknown idea for %s: %s" % (tag, value))
            lines.append("add_ideas = " + value)
        elif kind == "drop":
            if value not in IDEAS:
                raise ValueError("Unknown idea to remove: " + value)
            lines.append("if = { limit = { has_idea = %s } remove_ideas = %s }" % (value, value))
        elif kind == "tech":
            if value not in TECH_CATEGORIES:
                raise ValueError("Unreviewed technology category: " + value)
            lines.append("add_tech_bonus = { name = %s bonus = 0.5 uses = 1 category = %s }" % (bonus_name, value))
        elif kind == "xp":
            branch, amount = value.split("+")
            if branch != "army":
                raise ValueError("Unsupported experience branch: " + branch)
            lines.append("army_experience = %d" % int(amount))
        elif kind == "stab":
            lines.append("add_stability = %s" % float(value))
        elif kind == "ws":
            lines.append("add_war_support = %s" % float(value))
        elif kind == "event":
            trailing.append("country_event = { id = %s }" % event_id(int(value)))
        elif kind == "regime":
            if REGIMES.get(value, {}).get("tag") != tag:
                raise ValueError("Unknown regime for %s: %s" % (tag, value))
            lines.insert(0, "ac_ud_partners_regime_%s = yes" % value)
        elif kind == "flag":
            if value not in PATH_FLAGS:
                raise ValueError("Unlabelled path flag: " + value)
            lines.append("set_country_flag = " + value)
    if prep:
        programme.append(block("if", "limit = { date < 1999.7.8 }\n" + "\n".join(prep)).rstrip("\n"))
    if programme:
        # Extend the existing national programme contract (tools/usean_partners): its
        # indices and preparation credit are bounded and recalculated by their owner.
        lines.append(block("if", "limit = { has_country_flag = ac_up_initialized }\n" + "\n".join(programme)
                           + "\nac_up_bound = yes\nac_up_recalculate = yes").rstrip("\n"))
    return "\n".join(lines + trailing)


def gate_text(focus):
    rows = ["original_tag = %s tag = %s" % (focus.tag, focus.tag)]
    for key in focus.gates:
        condition, tooltip = GATES[key]
        rows.append("custom_trigger_tooltip = { tooltip = %s %s }" % (tooltip, condition))
    return "\n".join(rows)


def exclusive_map():
    pairs = {row.id: set(row.exclusive) for row in FOCUSES}
    for row in FOCUSES:
        for other in row.exclusive:
            if BY_ID[other].tag != row.tag:
                raise ValueError("Cross-country exclusivity: " + row.id)
            pairs[other].add(row.id)
    return pairs


def focus_node(row, exclusive):
    body = "id = %s\nicon = GFX_ac_ud_focus_%s\nx = %d\ny = %d\ncost = %d\n" % (row.id, row.id, row.x, row.y, row.cost)
    for group in row.prerequisites:
        body += block("prerequisite", " ".join("focus = " + ident for ident in group))
    if exclusive[row.id]:
        body += block("mutually_exclusive", " ".join("focus = " + ident for ident in sorted(exclusive[row.id], key=lambda i: BY_ID[i].order)))
    body += block("available", gate_text(row))
    if "prewin" in row.gates:
        body += block("bypass", "custom_trigger_tooltip = { tooltip = ac_ud_partners_gate_impact_tt date > 1999.7.7 }")
    body += block("ai_will_do", "factor = %d" % row.ai)
    effects = compile_reward(row.tag, row.reward, row.id)
    done = row.id + "_done"
    hidden = block("if", "limit = { NOT = { has_country_flag = %s } }\nset_country_flag = %s\n%s" % (done, done, effects))
    body += block("completion_reward", block("effect_tooltip", effects) + block("hidden_effect", hidden))
    political = row.x <= 40 and row.y <= 4
    body += "search_filters = { %s }\n" % ("FOCUS_FILTER_POLITICAL" if political else "FOCUS_FILTER_POLITICAL FOCUS_FILTER_INDUSTRY")
    return block("shared_focus", body)


def loc_line(key, value):
    value = value.replace("\n", "\\n").replace('"', "'")
    return ' %s:0 "%s"' % (key, value)


def outputs():
    out, loc = {}, {}

    def add_loc(key, value):
        if key in loc:
            raise ValueError("Duplicate localisation: " + key)
        loc[key] = value

    exclusive = exclusive_map()
    events = all_events()
    by_focus = {}
    for row in FOCUSES:
        for token in row.reward:
            if token.startswith("event:"):
                by_focus[int(token[6:])] = row
    if sorted(by_focus) != [event["n"] for event in events]:
        raise ValueError("Every event needs exactly one firing focus")

    # Focuses ---------------------------------------------------------------
    nodes = []
    for row in FOCUSES:
        nodes.append(focus_node(row, exclusive))
        add_loc(row.id, row.title)
        add_loc(row.id + "_desc", row.desc)
        add_loc(row.id + "_done", row.title + " completed")
    out["common/national_focus/ac_ud_partners.txt"] = NOTE + "\n".join(nodes)

    # Events ----------------------------------------------------------------
    texts = ["add_namespace = " + NAMESPACE + "\n"]
    for event in events:
        ident = event_id(event["n"])
        if event["tag"] != by_focus[event["n"]].tag or event["picture"] not in PICTURES:
            raise ValueError("Event owner or picture mismatch: " + ident)
        desc = seams.event_text(event["paragraphs"], event["layer"], event["citation"])
        problems = seams.event_problems(desc)
        if problems:
            raise ValueError(ident + ": " + ", ".join(problems))
        add_loc(ident + ".t", event["title"])
        add_loc(ident + ".d", desc)
        body = "id = %s\ntitle = %s.t\ndesc = %s.d\npicture = GFX_ac_ud_event_%s\nis_triggered_only = yes\n" % (ident, ident, ident, event["picture"])
        body += block("trigger", "original_tag = %s" % event["tag"])
        for index, (text, weight, reward) in enumerate(event["options"]):
            key = "%s.%s" % (ident, "abc"[index])
            add_loc(key, text)
            tokens = tuple(reward.split(";")) if reward else ()
            if any(t.startswith(("regime:", "event:")) for t in tokens):
                raise ValueError(ident + ": options may not reach a regime effect or chain an event")
            option = "name = %s\nai_chance = { factor = %d }\n%s" % (key, weight, compile_reward(event["tag"], tokens, ident + ".t"))
            body += block("option", option)
        texts.append(block("country_event", body))
    out["events/ac_ud_partners.txt"] = NOTE + "\n".join(texts)

    # Ideas -----------------------------------------------------------------
    ideas = []
    for ident, (title, desc, modifier, _subjects) in IDEAS.items():
        add_loc(ident, title)
        add_loc(ident + "_desc", desc + " Provisional gameplay.")
        ideas.append(block(ident, "picture = ac_ud_%s\nallowed = { always = no }\nallowed_civil_war = { always = no }\nremoval_cost = -1\n%s"
                           % (ident, block("modifier", modifier))))
    out["common/ideas/ac_ud_partners.txt"] = NOTE + block("ideas", block("country", "\n".join(ideas)))

    # Governments: regime effects and unnamed office leaders ----------------
    effects, characters = [], []
    for slug, row in REGIMES.items():
        character, body = seams.office_character(row["tag"], row["office"], row["sub"], portrait(office(slug)))
        characters.append(body)
        add_loc(character, row["name"])
        add_loc(character + "_desc", row["desc"])
        if sum(row["popularities"].values()) != 100:
            raise ValueError("Popularities must total 100: " + slug)
        name, effect = seams.regime_effect(PACKAGE, slug, row["party"], character, row["sub"], row["elections"], row["popularities"])
        effects.append(effect)
    out["common/scripted_effects/ac_ud_partners.txt"] = NOTE + "\n".join(effects)
    out["common/characters/ac_ud_partners.txt"] = NOTE + "characters = {\n" + "".join(characters) + "}\n"
    out["common/scripted_triggers/ac_ud_partners.txt"] = NOTE + block(
        "ac_ud_partners_postwar",
        "OR = {\n\tac_ucw_war_over = yes\n\thas_global_flag = ac_ucw_war_averted\n\tAND = { date > 2005.12.30 NOT = { has_global_flag = ac_ucw_war_started } }\n}")
    add_loc("ac_ud_partners_postwar", "The Continental War is over, was averted, or never began by the end of 2005")

    # Labels ----------------------------------------------------------------
    for key, text in GATE_TEXT.items():
        add_loc(key, text)
    for key, text in PATH_FLAGS.items():
        add_loc(key, text)
    add_loc("ac_up_initialized", "The national service programme has been initialised")

    # Sprites ---------------------------------------------------------------
    sprites = []
    for row in FOCUSES:
        sprites.extend(seams.focus_sprites(PACKAGE, row.id))
    for ident in IDEAS:
        sprites.append('spriteType = { name = "GFX_idea_ac_ud_%s" texturefile = "gfx/AC_usea_depth/partners/ideas/%s.dds" }' % (ident, ident))
    for slug in REGIMES:
        ident = office(slug)
        sprites.append('spriteType = { name = "%s" texturefile = "gfx/AC_usea_depth/partners/portraits/%s.dds" }' % (portrait(ident), ident))
    for picture in PICTURES:
        sprites.append('spriteType = { name = "GFX_ac_ud_event_%s" texturefile = "gfx/AC_usea_depth/partners/events/%s.dds" }' % (picture, picture))
    out["interface/ac_ud_partners.gfx"] = "spriteTypes = {\n" + "\n".join("\t" + s for s in sprites) + "\n}\n"

    out["localisation/english/ac_ud_partners_l_english.yml"] = "﻿l_english:\n" + "\n".join(loc_line(k, v) for k, v in loc.items()) + "\n"
    return out


def budget():
    counts = {tag: sum(row.tag == tag for row in FOCUSES) for tag in COUNTRIES}
    if counts != BUDGET:
        raise ValueError("Focus counts differ from the planned package budget: %s" % counts)
    return {"package": PACKAGE, "marker": MARKER, "focuses": counts,
            "trees": {COUNTRIES[tag]["tree"]: counts[tag] for tag in COUNTRIES}, "events": len(all_events())}


def tree_ids(tag):
    return [row.id for row in FOCUSES if row.tag == tag]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    failures = []
    files = {MOD / relative: text for relative, text in outputs().items()}
    files[HERE / "budget.json"] = json.dumps(budget(), indent=2) + "\n"
    for path, text in files.items():
        if args.check:
            if not path.exists() or path.read_bytes().replace(b"\r\n", b"\n") != text.encode("utf-8"):
                failures.append(path.relative_to(ROOT).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(text.encode("utf-8"))
    name, wrappers = seams.MARKERS[PACKAGE]
    if name != MARKER:
        raise SystemExit("Marker name differs from the seams contract")
    for wrapper in wrappers:
        tag = wrapper[:3]
        if not seams.attach_file(seams.FOCUS / wrapper, MARKER, tree_ids(tag), check=args.check) and args.check:
            failures.append("mod/2985041246/common/national_focus/" + wrapper)
    if failures:
        raise SystemExit("Usea Depth partners output differs: " + ", ".join(failures))
    print("Usea Depth partners: %d focuses, %d events, %d ideas, %d governments; %s"
          % (len(FOCUSES), len(all_events()), len(IDEAS), len(REGIMES), "consistent" if args.check else "generated"))


if __name__ == "__main__":
    main()
