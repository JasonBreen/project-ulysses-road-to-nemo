def outputs():
    excl = exclusions()
    focus = HEADER + "\n".join(focus_text(row, excl[row.id]) for row in C.FOCUSES)
    files = OrderedDict()
    files["common/national_focus/ac_ud_eru.txt"] = focus
    files["events/ac_ud_eru.txt"] = events_text()
    files["common/ideas/ac_ud_eru.txt"] = ideas_text()
    files["common/scripted_effects/ac_ud_eru.txt"] = effects_text()
    files["common/scripted_triggers/ac_ud_eru.txt"] = triggers_text()
    files["common/characters/ac_ud_eru.txt"] = characters_text()
    files["common/on_actions/ac_ud_eru.txt"] = on_actions_text()
    script = "\n".join(files.values())
    out = OrderedDict((MOD / path, text.encode("utf-8")) for path, text in files.items())
    out[MOD / "localisation/english/ac_ud_eru_l_english.yml"] = localisation(script).encode("utf-8")
    out[HERE / "budget.json"] = (json.dumps(budget(), indent=1) + "\n").encode("utf-8")
    out[ROOT / "docs/usea_depth/ERU.md"] = ledger().encode("utf-8")
    out.update(build_art.outputs())
    return out


def import_ids():
    opening = [row.id for row in C.FOCUSES if row.tree == "opening"]
    war = [row.id for row in C.FOCUSES if row.tree == "war"]
    return {"ERU_opening.txt": opening, "ERU.txt": war}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, data in outputs().items():
        if args.check:
            current = path.read_bytes() if path.exists() else None
            if current is not None and path.suffix in (".txt", ".yml", ".gfx", ".md", ".json"):
                current = current.replace(b"\r\n", b"\n")   # Git may check text out with CRLF on Windows
            if current != data:
                stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    for wrapper, ids in import_ids().items():
        assert wrapper in WRAPPERS, wrapper
        if not seams.attach_file(seams.FOCUS / wrapper, MARKER, ids, check=args.check) and args.check:
            stale.append("mod/2985041246/common/national_focus/" + wrapper + " (" + MARKER + " block)")
    if stale:
        raise SystemExit("Erusea package differs (run tools/usea_depth/eru/build.py, then the owner generators): " + ", ".join(stale[:25]))
    counts = budget()
    print("Erusea package %s: %d focuses (%s), %d events" % ("consistent" if args.check else "written", counts["focuses"]["ERU"],
          ", ".join("%s %d" % item for item in counts["trees"].items()), counts["events"]))
    if not args.check:
        print("Now re-run: python -B tools/usea_expansion/build_content.py && python -B tools/build_continental_war.py")


if __name__ == "__main__":
    main()
